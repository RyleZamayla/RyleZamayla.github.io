/*
 * 10 x 10 pixel icons drawn from character maps.
 * "#" = main colour, "+" = accent colour, anything else = empty.
 */
const MAPS = {
  Backend: ["##########", "#........#", "#.++.....#", "##########", "#........#", "#.++.....#", "##########", "#........#", "#.++.....#", "##########"],
  Mobile: ["..######..", "..#....#..", "..#++++#..", "..#++++#..", "..#++++#..", "..#++++#..", "..#++++#..", "..#....#..", "..#.##.#..", "..######.."],
  Integrations: ["..#....#..", "..#....#..", ".########.", ".#++++++#.", ".#++++++#.", "..#++++#..", "...####...", "....##....", "....##....", "....##...."],
  Security: [".########.", ".#++++++#.", ".#++++++#.", ".#++##++#.", ".#++##++#.", "..#++++#..", "..#++++#..", "...#++#...", "....##....", ".........."],
  Frontend: ["##########", "#+#+#....#", "##########", "#........#", "#.++++...#", "#........#", "#.++.++..#", "#........#", "#........#", "##########"],
  Tooling: ["......##..", ".....#..#.", "......#.#.", ".....####.", "....###...", "...###....", "..###.....", ".###......", "###.......", ".#........"],
  main: ["....##....", "....##....", "...####...", "##########", ".########.", "..######..", "..######..", ".###..###.", ".##....##.", ".........."],
  side: [".########.", "#++++++++#", ".#......#.", ".#.####.#.", ".#......#.", ".#.###..#.", ".#......#.", ".#.####.#.", "#++++++++#", ".########."],
} as const;

export type PixelIconName = keyof typeof MAPS;

export function PixelIcon({
  name,
  color = "#6fd3a6",
  accent = "#ff9e5e",
  size = 20,
}: {
  name: PixelIconName;
  color?: string;
  accent?: string;
  size?: number;
}) {
  return (
    <svg viewBox="0 0 10 10" width={size} height={size} shapeRendering="crispEdges" aria-hidden="true" className="pixel-icon">
      {MAPS[name].flatMap((row, y) =>
        [...row].map((ch, x) =>
          ch === "#" || ch === "+" ? (
            <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={ch === "#" ? color : accent} />
          ) : null,
        ),
      )}
    </svg>
  );
}
